def main(out):
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "Worksheet"
    ws.append(HEAD)
    for no, co, val, stage, rep, change in ROWS:
        ws.append([no, co, "", val, stage, "", rep, rep, "", "1405/01/01", change])
    wb.save(out)
    print(out, len(ROWS), "rows")


if __name__ == "__main__":
    main(sys.argv[1])
