    ("7103", "مشتری ج", 50000000, "بستن", "پویا تازه", "14:00:00 1405/06/20"),       # کارشناسِ ناشناخته → «نامِ تازه»
    ("7002", "رستوران نمونه", 500000000, "بستن", "سارا آزمون", "10:00:00 1405/07/02"),  # عیناً همان سندِ موجود → تکراری
    ("7001", "کافه دیگر", 500000000, "بستن", "سارا آزمون", "16:32:51 1405/07/05"),     # نامِ مشتریِ دیگر → تعارض
    ("7104", "مشتری د", 30000000, "بستن", "سارا آزمون", "08:00:00 1405/06/02"),
    ("7104", "مشتری د", 31000000, "بستن", "سارا آزمون", "08:00:00 1405/06/02"),        # همان شماره، مبلغِ دیگر → هر دو تعارض
